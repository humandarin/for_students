#include <iostream>
#include <windows.h>
using namespace std;

int main()
{
	setlocale(0, "");

	//переменная для числа которое мы вводим
	int inputNum;
	//переменная которая считает количество чисел
	int qtyNum = 0;

	//выводим название программы
	cout << "Подсчет чисел\n\n";
	
	//переменная-проверка, которая решает работает ли цикл
	bool check = true;

	//цикл, который работает, пока check = true, а иначе цикл завершается
	while (check) {
		cout << "Введите число: "; //вывыдим сообщение
		cin >> inputNum; //принимаем от пользвателя число
		if (inputNum == 0) { //если пользователь ввел 0, то check делаем false
			check = false; //завершаем работу цикла
		}
		else { //а иначе
			qtyNum++; //к переменной-счетчику чисел прибавляем +1 число
		}
	}


	//выводим итоговое количество чисел
	cout << "\n\nКоличество чисел: " << qtyNum;







	int _; cin >> _;
}




